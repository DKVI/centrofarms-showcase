(() => {
  const zoom = document.querySelector('#productZoom');
  document.querySelector('[data-product-zoom]')?.addEventListener('click', () => {
    if (zoom && !zoom.open) zoom.showModal();
  });
  const details = document.querySelector('[data-product-details]');
  if (!details) return;
  const tabs = [...details.querySelectorAll('[role="tab"]')];
  function select(tab) {
    tabs.forEach(button => {
      const active = button === tab;
      button.setAttribute('aria-selected', String(active));
      button.tabIndex = active ? 0 : -1;
      document.getElementById(button.getAttribute('aria-controls')).hidden = !active;
    });
  }
  tabs.forEach((tab, index) => {
    tab.addEventListener('click', () => select(tab));
    tab.addEventListener('keydown', event => {
      let next;
      if (event.key === 'ArrowRight') next = (index + 1) % tabs.length;
      if (event.key === 'ArrowLeft') next = (index - 1 + tabs.length) % tabs.length;
      if (event.key === 'Home') next = 0;
      if (event.key === 'End') next = tabs.length - 1;
      if (next === undefined) return;
      event.preventDefault();
      select(tabs[next]);
      tabs[next].focus();
    });
  });
})();
